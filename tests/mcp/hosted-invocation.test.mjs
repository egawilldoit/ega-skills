import assert from "node:assert/strict";
import { cpSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import test from "node:test";
import { createEnvelope, sha256Hex } from "../../packages/hashing/dist/index.js";
import { approvalSetDigest, buildHubRelease, buildInvocationHubRelease, createArtifactCandidate, createInvocationCandidate, createInvocationReleaseDiff, writeArtifactCandidate, writeInvocationCandidate } from "../../packages/project/dist/index.js";
import { createHostedMcpHandler, createRetainedManifest, loadHostedReleaseSnapshot, loadRetainedReleaseSet, promoteRetainedRelease, rollbackRetainedRelease } from "../../packages/mcp/dist/index.js";

test("hosted I1 activation verifies sidecars and resolves with the release policy", async (t) => {
  const root = mkdtempSync(join(tmpdir(), "ega-hosted-i1-"));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  const hub = join(root, "hub");
  mkdirSync(join(hub, "owned", "ega", "alpha"), { recursive: true });
  writeFileSync(join(hub, "owned", "ega", "alpha", "SKILL.md"), "---\nname: alpha\ndescription: alpha skill\n---\n\nUse alpha.\n");
  writeFileSync(join(hub, "hub.yaml"), "schema_version: 1\nhub:\n  id: hosted-i1\nowned:\n  - path: owned/ega\n    namespace: ega\nexternal: []\n");
  writeFileSync(join(hub, "sources.yaml"), "schema_version: 1\nsources: {}\n");
  writeFileSync(join(hub, "sources.lock.yaml"), "schema_version: 1\nsources: {}\n");
  const base = await buildHubRelease(hub);
  const policy = createEnvelope({ object_type: "ega.invocation-policy", schema_version: 1, payload: { profile: "ega-invocation-policy-v1", sources: [], bindings: [] } });
  const build = await buildInvocationHubRelease(hub, policy);
  const digest = `sha256:${"1".repeat(64)}`;
  const reviews = Object.entries(base.release.payload.skill_versions).map(([skill_id, version_hash]) => ({ skill_id, version_hash, candidate_digest: digest, review_digest: digest, decision: "APPROVED", revision: 1 }));
  const preflight = createEnvelope({ object_type: "ega.publication-preflight", schema_version: 2, payload: { approval_set_digest: approvalSetDigest(reviews), blockers: [], hub_id: base.release.payload.hub_id, reviews, skill_versions: base.release.payload.skill_versions, status: "READY" } });
  const diff = createInvocationReleaseDiff({ release: base.release }, { release: build.release, policy });
  const candidate = createInvocationCandidate(build, policy, base.release, preflight, diff);
  const dir = join(root, "candidate");
  writeInvocationCandidate(build, dir, candidate, base.release, preflight, diff);
  const snapshot = loadHostedReleaseSnapshot(dir);
  assert.equal(snapshot.invocation.policy.digest, policy.digest);
  const handler = createHostedMcpHandler(snapshot, { allowedOrigins: ["http://localhost"], verifyBearer: async () => ({ subject: "test", scopes: ["ega:read"] }), authorize: async () => true });
  const response = await handler.fetch(new Request("http://localhost/mcp", { method: "POST", headers: { authorization: "Bearer test", "content-type": "application/json", accept: "application/json, text/event-stream", origin: "http://localhost" }, body: JSON.stringify({ jsonrpc: "2.0", id: 1, method: "tools/call", params: { name: "resolve", arguments: { task: "alpha", explicit_skills: ["ega/alpha"] } } }) }));
  assert.equal(response.status, 200);
  const text = await response.text();
  const rpc = JSON.parse(text.match(/data: (.+)/)?.[1] ?? text);
  assert.notEqual(rpc.result.isError, true, JSON.stringify(rpc));
  assert.equal(rpc.result.structuredContent.result.router_contract_version, 2);
  assert.equal(rpc.result.structuredContent.result.explicit[0].id, "ega/alpha");
  const legacy = join(root, "legacy");
  const legacyCandidate = createArtifactCandidate(base);
  writeArtifactCandidate(base, legacy, legacyCandidate);
  const manifestPath = join(root, "retained.json");
  writeFileSync(manifestPath, JSON.stringify(createRetainedManifest({ hub_id: "hosted-i1", publication_revision: 1, deployment_id: "old", default_release_digest: base.release.digest, releases: [{ artifact_path: "legacy", candidate_digest: legacyCandidate.digest, release_digest: base.release.digest, release_package_digest: `sha256:${sha256Hex(readFileSync(join(legacy, "release-package.json")))}` }] })));
  promoteRetainedRelease({ manifestPath, candidatePath: join(dir, "candidate.json"), candidateDigest: candidate.digest, expectedRevision: 1, deploymentId: "new" });
  assert.equal(loadRetainedReleaseSet(manifestPath).defaultSnapshot.releaseDigest, build.release.digest);
  rollbackRetainedRelease({ manifestPath, candidatePath: join(legacy, "candidate.json"), candidateDigest: legacyCandidate.digest, releaseDigest: base.release.digest, expectedRevision: 2, deploymentId: "rollback", legacy: true });
  assert.equal(loadRetainedReleaseSet(manifestPath).defaultSnapshot.releaseDigest, base.release.digest);
  const broken = join(root, "broken");
  cpSync(dir, broken, { recursive: true });
  rmSync(join(broken, "invocation-policy.json"));
  assert.throws(() => loadHostedReleaseSnapshot(broken));
});
