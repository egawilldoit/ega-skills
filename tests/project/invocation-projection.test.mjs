import { test } from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createEnvelope } from '../../packages/hashing/dist/index.js';
import { createImportPlan, emptyRegistryTarget } from '../../packages/registry/dist/index.js';
import { acquireSource, releaseAcquiredSource, createAdoptionPlan, readHubIntakeState, stageAdoptionPlan, buildHubRelease, projectInvocationRelease, applyAdoptionPlan, writeCandidateReview, buildInvocationHubRelease } from '../../packages/project/dist/index.js';

const skill = name => `---\nname: ${name}\ndescription: ${name} projection fixture.\n---\n\nInstructions.\n`;
function git(dir, ...args) { return execFileSync('git', ['-C', dir, '-c', 'user.name=test', '-c', 'user.email=test@example.test', ...args], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim(); }
test('projection is deterministic, fails closed and matches the governed build after fixture adoption', async t => {
  const base = mkdtempSync(join(tmpdir(), 'ega-projection-'));
  t.after(() => rmSync(base, { recursive: true, force: true }));
  const hub = join(base, 'hub'), repo = join(base, 'repo');
  mkdirSync(join(hub, 'owned', 'ega', 'old'), { recursive: true });
  writeFileSync(join(hub, 'owned', 'ega', 'old', 'SKILL.md'), skill('old'));
  writeFileSync(join(hub, 'hub.yaml'), 'schema_version: 1\nhub:\n  id: personal\nowned:\n  - path: owned/ega\n    namespace: ega\nexternal: []\n');
  writeFileSync(join(hub, 'sources.yaml'), 'schema_version: 1\nsources: {}\n');
  writeFileSync(join(hub, 'sources.lock.yaml'), 'schema_version: 1\nsources: {}\n');
  mkdirSync(join(repo, 'skills', 'alpha'), { recursive: true });
  writeFileSync(join(repo, 'skills', 'alpha', 'SKILL.md'), skill('alpha'));
  writeFileSync(join(repo, 'LICENSE'), 'MIT\n');
  git(repo, 'init', '-b', 'main'); git(repo, 'add', '.'); git(repo, 'commit', '-m', 'fixture');
  const commit = git(repo, 'rev-parse', 'HEAD');
  const acquired = acquireSource({ source: repo, sourceType: 'git', ref: 'main', commit, roots: ['skills/alpha'], provenanceFiles: ['LICENSE'] });
  const importPlan = await createImportPlan({ sourcePath: acquired.snapshotDir, namespace: 'test', target: emptyRegistryTarget() });
  const plan = createAdoptionPlan({ source: acquired, sourceId: 'fixture', namespace: 'test', hub: readHubIntakeState(hub), importPlan });
  releaseAcquiredSource(acquired);
  await stageAdoptionPlan(plan, hub);
  const baseline = await buildHubRelease(hub);
  t.after(() => rmSync(baseline.registryHome, { recursive: true, force: true }));
  const version = plan.payload.candidates[0].version_hash;
  const payload = { profile: 'ega-invocation-policy-v1', sources: [{ source_id: 'fixture', repository: repo, resolved_commit: commit, governed_skill_ids: ['test/alpha'] }], bindings: [{ source_id: 'fixture', skill_id: 'test/alpha', version_hash: version, rules: [{ id: 'alpha', alternatives: [[{ literal: 'review' }, { literal: 'alpha' }]] }] }] };
  const policy = createEnvelope({ object_type: 'ega.invocation-policy', schema_version: 1, payload });
  const args = { hubDir: hub, baseline: baseline.release, plan, policy };
  const first = await projectInvocationRelease(args);
  assert.equal((await projectInvocationRelease(args)).digest, first.digest);
  assert.equal(first.payload.skill_versions['ega/old'], baseline.release.payload.skill_versions['ega/old']);
  assert.equal(first.payload.skill_versions['test/alpha'], version);
  const altered = structuredClone(policy); altered.payload.bindings[0].version_hash = `sha256:${'a'.repeat(64)}`;
  await assert.rejects(projectInvocationRelease({ ...args, policy: altered }));
  const stalePolicy = createEnvelope({ object_type: 'ega.invocation-policy', schema_version: 1, payload: altered.payload });
  await assert.rejects(projectInvocationRelease({ ...args, policy: stalePolicy }), /binding mismatch/);
  const wrongBaseline = structuredClone(baseline.release); wrongBaseline.digest = `sha256:${'a'.repeat(64)}`;
  await assert.rejects(projectInvocationRelease({ ...args, baseline: wrongBaseline }));
  const owned = join(hub, 'owned', 'ega', 'old', 'SKILL.md');
  const ownedOriginal = readFileSync(owned); writeFileSync(owned, skill('old') + 'changed');
  await assert.rejects(projectInvocationRelease(args), /stale/); writeFileSync(owned, ownedOriginal);
  const stage = join(hub, '.intake-staging', plan.digest.slice(7), 'source', 'skills', 'alpha', 'SKILL.md');
  const original = readFileSync(stage); writeFileSync(stage, 'tampered');
  await assert.rejects(projectInvocationRelease(args)); writeFileSync(stage, original);
  writeCandidateReview({ candidate: plan, decision: 'APPROVED', expectedRevision: 0, hubDir: hub });
  await applyAdoptionPlan({ hubDir: hub, plan });
  const adopted = await buildInvocationHubRelease(hub, policy);
  t.after(() => rmSync(adopted.registryHome, { recursive: true, force: true }));
  assert.equal(adopted.release.digest, first.digest);
  await assert.rejects(projectInvocationRelease(args));
});
