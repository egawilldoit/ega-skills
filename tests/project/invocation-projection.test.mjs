import { createHostedMcpHandler, loadHostedReleaseSnapshot } from '../../packages/mcp/dist/index.js';

const skill = name => `---\nname: ${name}\ndescription: ${name} projection fixture.\n---\n\nInstructions.\n`;
function git(dir, ...args) { return execFileSync('git', ['-C', dir, '-c', 'user.name=test', '-c', 'user.email=test@example.test', ...args], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim(); }
test('projection is deterministic, fails closed and matches the governed build after fixture adoption', async t => {
  const base = mkdtempSync(join(tmpdir(), 'ega-projection-'));
  t.after(() => rmSync(base, { recursive: true, force: true }));
  const hub = join(base, 'hub'), repo = join(base, 'repo');
  mkdirSync(join(hub, 'owned', 'ega', 'old'), { recursive: true });
  writeFileSync(join(hub, 'owned', 'ega', 'old', 'SKILL.md'), skill('old'));
  writeFileSync(join(hub, 'hub.yaml'), 'schema_version: 1\nhub:\n  id: personal\nowned:\n  - path: owned/ega\n    namespace: ega\nexternal: []\n');
  writeFileSync(join(hub, 'sources.yaml'), 'schema_version: 1\nsources: {}\n');
  writeFileSync(join(hub, 'sources.lock.yaml'), 'schema_version: 1\nsources: {}\n');
  mkdirSync(join(repo, 'skills', 'alpha'), { recursive: true });
  writeFileSync(join(repo, 'skills', 'alpha', 'SKILL.md'), skill('alpha'));
  writeFileSync(join(repo, 'LICENSE'), 'MIT\n');
  git(repo, 'init', '-b', 'main'); git(repo, 'add', '.'); git(repo, 'commit', '-m', 'fixture');
  const commit = git(repo, 'rev-parse', 'HEAD');
  const acquired = acquireSource({ source: repo, sourceType: 'git', ref: 'main', commit, roots: ['skills/alpha'], provenanceFiles: ['LICENSE'] });
  const importPlan = await createImportPlan({ sourcePath: acquired.snapshotDir, namespace: 'test', target: emptyRegistryTarget() });
  const plan = createAdoptionPlan({ source: acquired, sourceId: 'fixture', namespace: 'test', hub: readHubIntakeState(hub), importPlan });
  releaseAcquiredSource(acquired);
  await stageAdoptionPlan(plan, hub);
  const baseline = await buildHubRelease(hub);
  t.after(() => rmSync(baseline.registryHome, { recursive: true, force: true }));
  const version = plan.payload.candidates[0].version_hash;
  const payload = { profile: 'ega-invocation-policy-v1', sources: [{ source_id: 'fixture', repository: repo, resolved_commit: commit, governed_skill_ids: ['test/alpha'] }], bindings: [{ source_id: 'fixture', skill_id: 'test/alpha', version_hash: version, rules: [{ id: 'alpha', alternatives: [[{ literal: 'review' }, { literal: 'alpha' }]] }] }] };
  const policy = createEnvelope({ object_type: 'ega.invocation-policy', schema_version: 1, payload });
  const args = { hubDir: hub, baseline: baseline.release, plan, policy };
  const first = await projectInvocationRelease(args);
  assert.equal((await projectInvocationRelease(args)).digest, first.digest);
  const baselinePath = join(base, 'baseline.json'), planPath = join(base, 'plan.json'), policyPath = join(base, 'policy.json');
  writeFileSync(baselinePath, JSON.stringify(baseline.release));
  writeFileSync(planPath, JSON.stringify(plan));
  writeFileSync(policyPath, JSON.stringify(policy));
  const cli = join(process.cwd(), 'packages/cli/bin/ega-skills.mjs');
  const projected = JSON.parse(execFileSync(process.execPath, [cli, 'hub', 'release', 'project', '--hub', hub, '--against', baselinePath, '--plan', planPath, '--policy', policyPath], { encoding: 'utf8' }));
  assert.equal(projected.digest, first.digest);
  assert.equal(first.payload.skill_versions['ega/old'], baseline.release.payload.skill_versions['ega/old']);
  assert.equal(first.payload.skill_versions['test/alpha'], version);
  const altered = structuredClone(policy); altered.payload.bindings[0].version_hash = `sha256:${'a'.repeat(64)}`;
  await assert.rejects(projectInvocationRelease({ ...args, policy: altered }));
  const stalePolicy = createEnvelope({ object_type: 'ega.invocation-policy', schema_version: 1, payload: altered.payload });
  await assert.rejects(projectInvocationRelease({ ...args, policy: stalePolicy }), /binding mismatch/);
  const wrongBaseline = structuredClone(baseline.release); wrongBaseline.digest = `sha256:${'a'.repeat(64)}`;
  await assert.rejects(projectInvocationRelease({ ...args, baseline: wrongBaseline }));
  const owned = join(hub, 'owned', 'ega', 'old', 'SKILL.md');
  const ownedOriginal = readFileSync(owned); writeFileSync(owned, skill('old') + 'changed');
  await assert.rejects(projectInvocationRelease(args), /stale/); writeFileSync(owned, ownedOriginal);
  const stage = join(hub, '.intake-staging', plan.digest.slice(7), 'source', 'skills', 'alpha', 'SKILL.md');
  const original = readFileSync(stage); writeFileSync(stage, 'tampered');
  await assert.rejects(projectInvocationRelease(args)); writeFileSync(stage, original);
  writeCandidateReview({ candidate: plan, decision: 'APPROVED', expectedRevision: 0, hubDir: hub });
  await applyAdoptionPlan({ hubDir: hub, plan });
  const adopted = await buildInvocationHubRelease(hub, policy);
  t.after(() => rmSync(adopted.registryHome, { recursive: true, force: true }));
  assert.equal(adopted.release.digest, first.digest);
  verifyInvocationTransition({ release: adopted.release, policy }, { release: adopted.release, policy });
  const adoptedBase = await buildHubRelease(hub);
  t.after(() => rmSync(adoptedBase.registryHome, { recursive: true, force: true }));
  const emptyPolicy = createEnvelope({ object_type: 'ega.invocation-policy', schema_version: 1, payload: { profile: 'ega-invocation-policy-v1', sources: [], bindings: [] } });
  const ungoverned = createInvocationRelease(adoptedBase.release, emptyPolicy);
  assert.throws(() => verifyInvocationTransition({ release: adopted.release, policy }, { release: ungoverned, policy: emptyPolicy }), /migration/);
  assert.throws(() => verifyInvocationTransition({ release: adopted.release, policy }, { release: adoptedBase.release }), /migration/);
  const changedPayload = structuredClone(adoptedBase.release.payload);
  changedPayload.adopted_sources[0].source_config_digest = `sha256:${'a'.repeat(64)}`;
  const changedBase = createEnvelope({ object_type: 'ega.hub-release', schema_version: 1, payload: changedPayload });
  const changed = createInvocationRelease(changedBase, policy);
  assert.throws(() => verifyInvocationTransition({ release: adopted.release, policy }, { release: changed, policy }), /migration/);
  await assert.rejects(projectInvocationRelease(args));
});

test('governed CLI preview and export require approval and preserve the projected identity', async t => {
  const base = mkdtempSync(join(tmpdir(), 'ega-i1-cli-'));
  t.after(() => rmSync(base, { recursive: true, force: true }));
  const hub = join(base, 'hub'), repo = join(base, 'repo');
  mkdirSync(hub); mkdirSync(join(repo, 'skills', 'alpha'), { recursive: true });
  writeFileSync(join(hub, 'hub.yaml'), 'schema_version: 1\nhub:\n  id: personal\nowned: []\nexternal: []\n');
  writeFileSync(join(hub, 'sources.yaml'), 'schema_version: 1\nsources: {}\n');
  writeFileSync(join(hub, 'sources.lock.yaml'), 'schema_version: 1\nsources: {}\n');
  writeFileSync(join(repo, 'skills', 'alpha', 'SKILL.md'), skill('alpha'));
  writeFileSync(join(repo, 'LICENSE'), 'MIT\n');
  git(repo, 'init', '-b', 'main'); git(repo, 'add', '.'); git(repo, 'commit', '-m', 'fixture');
  const commit = git(repo, 'rev-parse', 'HEAD');
  const acquired = acquireSource({ source: repo, sourceType: 'git', ref: 'main', commit, roots: ['skills/alpha'], provenanceFiles: ['LICENSE'] });
  const importPlan = await createImportPlan({ sourcePath: acquired.snapshotDir, namespace: 'test', target: emptyRegistryTarget() });
  const plan = createAdoptionPlan({ source: acquired, sourceId: 'fixture', namespace: 'test', hub: readHubIntakeState(hub), importPlan });
  releaseAcquiredSource(acquired);
  await stageAdoptionPlan(plan, hub);
  const baseline = await buildHubRelease(hub);
  t.after(() => rmSync(baseline.registryHome, { recursive: true, force: true }));
  const policy = createEnvelope({ object_type: 'ega.invocation-policy', schema_version: 1, payload: { profile: 'ega-invocation-policy-v1', sources: [{ source_id: 'fixture', repository: repo, resolved_commit: commit, governed_skill_ids: ['test/alpha'] }], bindings: [{ source_id: 'fixture', skill_id: 'test/alpha', version_hash: plan.payload.candidates[0].version_hash, rules: [{ id: 'alpha', alternatives: [[{ literal: 'review' }, { literal: 'alpha' }]] }] }] } });
  const projected = await projectInvocationRelease({ hubDir: hub, baseline: baseline.release, plan, policy });
  const baselinePath = join(base, 'baseline.json'), policyPath = join(base, 'policy.json');
  writeFileSync(baselinePath, JSON.stringify(baseline.release)); writeFileSync(policyPath, JSON.stringify(policy));
  writeCandidateReview({ candidate: plan, decision: 'APPROVED', expectedRevision: 0, hubDir: hub });
  await applyAdoptionPlan({ hubDir: hub, plan });
  const cli = join(process.cwd(), 'packages/cli/bin/ega-skills.mjs'), candidate = join(base, 'candidate'), output = join(base, 'export');
  const previewArgs = [cli, 'hub', 'release', 'preview', '--hub', hub, '--against', baselinePath, '--policy', policyPath, '--output-dir', candidate];
  assert.throws(() => execFileSync(process.execPath, previewArgs, { encoding: 'utf8', stdio: 'pipe', env: { ...process.env, EGA_SKILLS_TRUSTED_PUBLISHED_RELEASE: `sha256:${'0'.repeat(64)}` } }), /current published release identity/);
  const preview = JSON.parse(execFileSync(process.execPath, previewArgs, { encoding: 'utf8', env: { ...process.env, EGA_SKILLS_TRUSTED_PUBLISHED_RELEASE: baseline.release.digest } }));
  assert.equal(preview.status, 'READY'); assert.equal(preview.candidate.payload.release_digest, projected.digest);
  const handler = createHostedMcpHandler(loadHostedReleaseSnapshot(candidate), { allowedOrigins: ['http://localhost'], verifyBearer: async () => ({ subject: 'test', scopes: ['ega:read'] }), authorize: async () => true });
  const resolveHosted = async task => {
    const response = await handler.fetch(new Request('http://localhost/mcp', { method: 'POST', headers: { authorization: 'Bearer test', 'content-type': 'application/json', accept: 'application/json, text/event-stream', origin: 'http://localhost' }, body: JSON.stringify({ jsonrpc: '2.0', id: 1, method: 'tools/call', params: { name: 'resolve', arguments: { task } } }) }));
    assert.equal(response.status, 200);
    const text = await response.text();
    return JSON.parse(text.match(/data: (.+)/)?.[1] ?? text).result.structuredContent.result;
  };
  assert.ok((await resolveHosted('review alpha')).selected.some(item => item.id === 'test/alpha'));
  assert.ok(!(await resolveHosted('alpha')).selected.some(item => item.id === 'test/alpha'));
  const exported = JSON.parse(execFileSync(process.execPath, [cli, 'hub', 'release', 'export', '--candidate', join(candidate, 'candidate.json'), '--out', output], { encoding: 'utf8' }));
  assert.equal(exported.release_digest, projected.digest);
  assert.throws(() => execFileSync(process.execPath, [cli, 'hub', 'release', 'export', '--candidate', join(candidate, 'candidate.json'), '--out', join(base, 'legacy'), '--legacy'], { stdio: 'ignore' }));
});
