async function localResolve(t, home, project, trustedRelease) {
  const child = spawn(process.execPath, [join(process.cwd(), "packages/mcp/bin/ega-mcp.mjs")], { cwd: project, env: { ...process.env, EGA_SKILLS_HOME: home, ...(trustedRelease ? { EGA_SKILLS_TRUSTED_RELEASE: trustedRelease } : {}) }, stdio: ["pipe", "pipe", "pipe"] });
  const closed = once(child, "close");
  child.stderr.resume();
  const pending = new Map();
  createInterface({ input: child.stdout }).on("line", line => { const msg = JSON.parse(line); pending.get(msg.id)?.(msg); pending.delete(msg.id); });
  const request = (id, method, params) => new Promise((resolve, reject) => {
    const timer = setTimeout(() => reject(new Error("local MCP timeout")), 15000);
    pending.set(id, msg => { clearTimeout(timer); resolve(msg); });
    child.stdin.write(`${JSON.stringify({ jsonrpc: "2.0", id, method, params })}\n`);
  });
  try {
    await request(1, "initialize", { protocolVersion: "2025-11-25", capabilities: {}, clientInfo: { name: "i1-test", version: "1" } });
    child.stdin.write(`${JSON.stringify({ jsonrpc: "2.0", method: "notifications/initialized" })}\n`);
    return (await request(2, "tools/call", { name: "resolve", arguments: { task: "alpha", explicit_skills: ["ega/alpha"] } })).result;
  } finally {
    child.stdin.end();
    if (child.exitCode === null && child.signalCode === null) child.kill();
    await closed;
  }
}

test("hosted I1 activation verifies sidecars and resolves with the release policy", async (t) => {
  const root = mkdtempSync(join(tmpdir(), "ega-hosted-i1-"));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  const hub = join(root, "hub");
  mkdirSync(join(hub, "owned", "ega", "alpha"), { recursive: true });
  writeFileSync(join(hub, "owned", "ega", "alpha", "SKILL.md"), "---\nname: alpha\ndescription: alpha skill\n---\n\nUse alpha.\n");
  writeFileSync(join(hub, "hub.yaml"), "schema_version: 1\nhub:\n  id: hosted-i1\nowned:\n  - path: owned/ega\n    namespace: ega\nexternal: []\n");
  writeFileSync(join(hub, "sources.yaml"), "schema_version: 1\nsources: {}\n");
  writeFileSync(join(hub, "sources.lock.yaml"), "schema_version: 1\nsources: {}\n");
  const base = await buildHubRelease(hub);
  const policy = createEnvelope({ object_type: "ega.invocation-policy", schema_version: 1, payload: { profile: "ega-invocation-policy-v1", sources: [], bindings: [] } });
  const build = await buildInvocationHubRelease(hub, policy);
  const digest = `sha256:${"1".repeat(64)}`;
  const reviews = Object.entries(base.release.payload.skill_versions).map(([skill_id, version_hash]) => ({ skill_id, version_hash, candidate_digest: digest, review_digest: digest, decision: "APPROVED", revision: 1 }));
  const preflight = createEnvelope({ object_type: "ega.publication-preflight", schema_version: 2, payload: { approval_set_digest: approvalSetDigest(reviews), blockers: [], hub_id: base.release.payload.hub_id, reviews, skill_versions: base.release.payload.skill_versions, status: "READY" } });
  const diff = createInvocationReleaseDiff({ release: base.release }, { release: build.release, policy });
  const candidate = createInvocationCandidate(build, policy, base.release, preflight, diff);
  const dir = join(root, "candidate");
  writeInvocationCandidate(build, dir, candidate, base.release, preflight, diff);
  const snapshot = loadHostedReleaseSnapshot(dir);
  assert.equal(snapshot.invocation.policy.digest, policy.digest);
  const direct = { task: "alpha", projectPath: root, env: { EGA_SKILLS_HOME: dir } };
  await assert.rejects(resolveSkills(direct), { code: "E_INVOCATION_POLICY_INVALID" });
  assert.equal((await resolveSkills({ ...direct, invocation: snapshot.invocation })).routerContractVersion, 2);
  const wrongRelease = createEnvelope({ object_type: "ega.hub-release", schema_version: 2, payload: { ...build.release.payload, hub_id: "different-hub" } });
  await assert.rejects(resolveSkills({ ...direct, invocation: { release: wrongRelease, policy } }), { code: "E_INVOCATION_POLICY_INVALID" });
  const handler = createHostedMcpHandler(snapshot, { allowedOrigins: ["http://localhost"], verifyBearer: async () => ({ subject: "test", scopes: ["ega:read"] }), authorize: async () => true });
  const response = await handler.fetch(new Request("http://localhost/mcp", { method: "POST", headers: { authorization: "Bearer test", "content-type": "application/json", accept: "application/json, text/event-stream", origin: "http://localhost" }, body: JSON.stringify({ jsonrpc: "2.0", id: 1, method: "tools/call", params: { name: "resolve", arguments: { task: "alpha", explicit_skills: ["ega/alpha"] } } }) }));
  assert.equal(response.status, 200);
  const text = await response.text();
  const rpc = JSON.parse(text.match(/data: (.+)/)?.[1] ?? text);
  assert.notEqual(rpc.result.isError, true, JSON.stringify(rpc));
  assert.equal(rpc.result.structuredContent.result.router_contract_version, 2);
  assert.equal(rpc.result.structuredContent.result.explicit[0].id, "ega/alpha");
  const local = await localResolve(t, dir, root);
  assert.equal(local.isError, false);
  assert.equal(local.structuredContent.result.router_contract_version, 2);
  assert.equal(local.structuredContent.result.explicit[0].id, "ega/alpha");
  const cli = spawnSync(process.execPath, [join(process.cwd(), "packages/cli/bin/ega-skills.mjs"), "resolve", "--project", root, "--task", "alpha", "--explicit", "ega/alpha"], { encoding: "utf8", timeout: 30000, env: { ...process.env, EGA_SKILLS_HOME: dir } });
  assert.equal(cli.status, 0, cli.stderr);
  assert.equal(JSON.parse(cli.stdout).routerContractVersion, 2);
  const legacy = join(root, "legacy");
  const legacyCandidate = createArtifactCandidate(base);
  writeArtifactCandidate(base, legacy, legacyCandidate);
  const manifestPath = join(root, "retained.json");
  writeFileSync(manifestPath, JSON.stringify(createRetainedManifest({ hub_id: "hosted-i1", publication_revision: 1, deployment_id: "old", default_release_digest: base.release.digest, releases: [{ artifact_path: "legacy", candidate_digest: legacyCandidate.digest, release_digest: base.release.digest, release_package_digest: `sha256:${sha256Hex(readFileSync(join(legacy, "release-package.json")))}` }] })));
  promoteRetainedRelease({ manifestPath, candidatePath: join(dir, "candidate.json"), candidateDigest: candidate.digest, expectedRevision: 1, deploymentId: "new" });
  assert.equal(loadRetainedReleaseSet(manifestPath).defaultSnapshot.releaseDigest, build.release.digest);
  const comparison = getReleaseComparison(parseServerConfig({ EGA_WEB_RETAINED_MANIFEST: manifestPath }), { base: base.release.digest, candidate: build.release.digest });
  assert.equal(comparison.status, "CHANGED");
  assert.equal(comparison.unchanged_count, 1);
  assert.deepEqual(comparison.added_skill_ids, []);
  assert.throws(() => promoteRetainedRelease({ manifestPath, candidatePath: join(dir, "candidate.json"), candidateDigest: candidate.digest, expectedRevision: 2, deploymentId: "stale-predecessor" }), /current release/);
  assert.throws(() => promoteRetainedRelease({ manifestPath, candidatePath: join(legacy, "candidate.json"), candidateDigest: legacyCandidate.digest, expectedRevision: 2, deploymentId: "forward-downgrade", legacy: true }), /current release/);
  rollbackRetainedRelease({ manifestPath, candidatePath: join(legacy, "candidate.json"), candidateDigest: legacyCandidate.digest, releaseDigest: base.release.digest, expectedRevision: 2, deploymentId: "rollback", legacy: true });
  assert.equal(loadRetainedReleaseSet(manifestPath).defaultSnapshot.releaseDigest, base.release.digest);
  const broken = join(root, "broken");
  cpSync(dir, broken, { recursive: true });
  rmSync(join(broken, "invocation-policy.json"));
  assert.throws(() => loadHostedReleaseSnapshot(broken));
  const localBroken = await localResolve(t, broken, root);
  assert.equal(localBroken.isError, true);
  assert.equal((localBroken.structuredContent.error ?? localBroken.structuredContent.result?.error)?.code, "E_INVOCATION_POLICY_INVALID", JSON.stringify(localBroken));
  const stripped = join(root, "stripped");
  cpSync(dir, stripped, { recursive: true });
  for (const file of ["hub-release.json", "candidate.json", "invocation-policy.json"]) rmSync(join(stripped, file));
  const localStripped = await localResolve(t, stripped, root);
  assert.equal(localStripped.isError, true);
  assert.equal((localStripped.structuredContent.error ?? localStripped.structuredContent.result?.error)?.code, "E_INVOCATION_POLICY_INVALID", JSON.stringify(localStripped));
  const Database = createRequire(new URL("../../packages/registry/package.json", import.meta.url))("better-sqlite3");
  const altered = new Database(join(stripped, "registry.sqlite"));
  altered.exec("DROP TABLE ega_invocation_profile; PRAGMA user_version = 2");
  altered.close();
  const localAltered = await localResolve(t, stripped, root, build.release.digest);
  assert.equal(localAltered.isError, true);
  assert.equal((localAltered.structuredContent.error ?? localAltered.structuredContent.result?.error)?.code, "E_INVOCATION_POLICY_INVALID", JSON.stringify(localAltered));
});
